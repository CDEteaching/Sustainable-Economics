"""Generate the chapter self-test quizzes from quizzes/quizzes.yml.

Writes <n>_<chapter folder>/_quiz.qmd for every chapter in the YAML file.
Each chapter .qmd includes its quiz at the end with {{< include _quiz.qmd >}}.

HTML: raw webexercises markup, checked by webex.js (already loaded in
_quarto.yml). Answers are coloured as soon as a student picks or types one,
and the explanation sits in a "Show explanation" toggle.
PDF: plain questions, followed by an answer key with the explanations.

Usage (from the repo root or anywhere): python quizzes/build_quizzes.py
Requires PyYAML (pip install pyyaml).
"""

import html
import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "quizzes" / "quizzes.yml"
LETTERS = "abcdefgh"


def esc(text):
    return html.escape(str(text), quote=True)


def correct_text(q):
    if q["type"] == "mcq":
        return f"{LETTERS[q['answer']]})"
    if q["type"] == "torf":
        return "True" if q["answer"] else "False"
    return " / ".join(f"“{a}”" for a in q["accept"])


def html_question(chapter, number, q):
    qid = f"q{chapter}-{number}"  # contains a letter g-z, so webex.js reads data-answer as plain JSON
    out = [
        '<div class="webex-box quiz-question">',
        f'<p class="quiz-meta">Question {chapter}.{number} &middot; Based on section {esc(q["section"])}</p>',
        f'<p class="quiz-stem">{esc(q["question"])}</p>',
    ]
    if q["type"] in ("mcq", "torf"):
        options = q["options"] if q["type"] == "mcq" else ["True", "False"]
        correct = q["answer"] if q["type"] == "mcq" else (0 if q["answer"] else 1)
        flags = [1 if i == correct else 0 for i in range(len(options))]
        out.append(f'<div class="webex-radiogroup" id="webex-{qid}" data-answer="{esc(json.dumps(flags))}">')
        for i, opt in enumerate(options):
            label = f"{LETTERS[i]}) {opt}" if q["type"] == "mcq" else opt
            out.append(f'<label><input type="radio" autocomplete="off" name="{qid}"><span>{esc(label)}</span></label>')
        out.append("</div>")
    else:
        answers = json.dumps([a.lower() for a in q["accept"]], ensure_ascii=False)
        out.append(
            f'<p><input class="webex-solveme ignorecase" id="webex-{qid}" size="20" '
            f'data-answer="{esc(answers)}" aria-label="Your answer"></p>'
        )
    out.append(f'<details class="quiz-feedback"><summary>Show explanation</summary><p>{esc(q["feedback"])}</p></details>')
    out.append("</div>")
    return "\n".join(out)


def pdf_question(chapter, number, q):
    out = [f"**Question {chapter}.{number}** (based on section {q['section']})", "", q["question"], ""]
    if q["type"] == "mcq":
        out += [f"{LETTERS[i]}) {opt}" for i, opt in enumerate(q["options"])]
    elif q["type"] == "torf":
        out += ["a) True", "b) False"]
    else:
        out.append("Answer: \\_\\_\\_\\_\\_\\_\\_\\_\\_\\_\\_\\_")
    out.append("")
    return "\n".join(out)


def build_chapter(ch):
    n, questions = ch["chapter"], ch["questions"]
    lines = [
        "<!-- Generated by quizzes/build_quizzes.py from quizzes/quizzes.yml. Do not edit by hand. -->",
        "",
        "## Self-test Quiz {.unnumbered}",
        "",
        f"Test your understanding of this chapter with {len(questions)} short questions. "
        "The quiz is voluntary and ungraded, and you can repeat it as often as you like.",
        "",
        '::: {.content-visible when-format="html"}',
        "Pick an answer (or type it in) to see at once whether it is correct, "
        "then open the explanation to see why.",
        "",
        "```{=html}",
    ]
    lines += [html_question(n, i, q) for i, q in enumerate(questions, 1)]
    lines += ["```", "", ":::", "", '::: {.content-visible when-format="pdf"}']
    lines += [pdf_question(n, i, q) for i, q in enumerate(questions, 1)]
    lines += ["#### Answers and explanations {.unnumbered}", ""]
    lines += [f"**{n}.{i}** {correct_text(q)}. {q['feedback']}\n" for i, q in enumerate(questions, 1)]
    lines += [":::", ""]
    return "\n".join(lines)


def main():
    data = yaml.safe_load(SOURCE.read_text(encoding="utf-8"))
    for ch in data["chapters"]:
        folders = sorted(ROOT.glob(f"{ch['chapter']}_*/"))
        if len(folders) != 1:
            raise SystemExit(f"Chapter {ch['chapter']}: expected one folder, found {folders}")
        target = folders[0] / "_quiz.qmd"
        target.write_text(build_chapter(ch), encoding="utf-8", newline="\n")
        print(f"{target.relative_to(ROOT)}: {len(ch['questions'])} questions")


if __name__ == "__main__":
    main()
